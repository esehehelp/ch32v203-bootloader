def main():
    rows = {}
    for line in GLYPHS.strip().splitlines():
        code, *art = line.split()
        assert len(art) == 7 and all(len(r) == 5 for r in art), line
        rows[int(code, 16)] = art
    assert sorted(rows) == list(range(0x20, 0x7F))

    print("/* Generated by tools/gen_font.py — 5x7 ASCII font, column-major, bit0 = top. */")
    print("/* SPDX-License-Identifier: MIT */")
    print("#ifndef FONT5X7_H")
    print("#define FONT5X7_H")
    print("#include <stdint.h>")
    print("#define FONT_FIRST 0x20")
    print("#define FONT_LAST  0x7E")
    print("static const uint8_t font5x7[][5] = {")
    for c in range(0x20, 0x7F):
        art = rows[c]
        cols = []
        for x in range(5):
            b = 0
            for y in range(7):
                if art[y][x] == "#":
                    b |= 1 << y
            cols.append(b)
        ch = chr(c)
        comment = ch if ch not in "\\*/" else " "
        print("    {%s}, /* %s */" % (", ".join("0x%02X" % v for v in cols), comment))
    print("};")
    print("#endif")


main()
